import { describe, expect, it } from "vitest";
import { findDangerousCommands } from "../src/core/dangerous-commands.ts";

describe("findDangerousCommands", () => {
	it.each([
		["rm file.txt", "rm"],
		["rm -rf build", "rm"],
		["cd x && /bin/rm -f a", "rm"],
		["\\rm a", "rm"],
		["sudo rm -rf /", "rm"],
		["find . -name '*.log' | xargs rm", "rm"],
		["git rm a", "git rm"],
		["git push origin main \\\n  --force", "git push --force"],
		["git reset \\\n --hard HEAD~1", "git reset --hard"],
		["r''m -rf x", "rm"],
		['bash -c "rm x"', "rm"],
		["find . -exec rm {} +", "rm"],
		["env FOO=1 rm a", "rm"],
		["xargs -0 rm", "rm"],
		["echo $(rm a)", "rm"],
		["git push origin --delete old", "git push --delete"],
		["git push origin :old", "git push --delete"],
		["git push --mirror", "git push --force"],
		["git switch --discard-changes main", "git switch --discard-changes"],
		["git checkout -B main origin/main", "git checkout (discard changes)"],
		["git branch -f main HEAD~3", "git branch -D"],
		["git restore --staged --worktree a", "git restore"],
		["git reflog expire --expire=now --all", "git reflog expire"],
		["git gc --prune=now", "git gc --prune"],
		["git filter-repo --path x", "git filter-branch"],
		["rsync -a --delete src/ dst/", "rsync --delete"],
		["truncate -s0 log", "truncate"],
		["rmdir empty", "rmdir"],
		["unlink a", "unlink"],
		["shred -u secret", "shred"],
		["find . -name '*.tmp' -delete", "find -delete"],
		["git push --force", "git push --force"],
		["git push -f origin main", "git push --force"],
		["git push --force-with-lease", "git push --force"],
		["git push origin +main", "git push --force"],
		["git -C repo push -uf origin x", "git push --force"],
		["git reset --hard HEAD~1", "git reset --hard"],
		["git clean -fd", "git clean"],
		["git checkout -- src/a.ts", "git checkout (discard changes)"],
		["git checkout .", "git checkout (discard changes)"],
		["git restore src/a.ts", "git restore"],
		["git branch -D feature", "git branch -D"],
		["git stash drop", "git stash drop/clear"],
		["sudo apt install x", "sudo"],
		["dd if=/dev/zero of=/dev/disk2", "dd"],
		["mkfs.ext4 /dev/sdb1", "mkfs"],
		["diskutil eraseDisk APFS X disk2", "diskutil erase"],
		["eval rm -rf x", "rm"],
		["timeout 5 rm -rf x", "rm"],
		["stdbuf -o0 rm x", "rm"],
		["git -c core.x=1 --no-pager -C repo rm a", "git rm"],
		["git worktree remove --force ../wt", "git worktree remove --force"],
		['bash -c "git push -f"', "git push --force"],
		['git -C "my dir" push -f', "git push --force"],
		["if git reset --hard; then echo; fi", "git reset --hard"],
		["until git push -f; do sleep 1; done", "git push --force"],
		["nice -n 5 git push -f", "git push --force"],
		["sudo -u bob rm x", "rm"],
		["ssh host git push -f", "git push --force"],
		["ssh host 'git reset --hard'", "git reset --hard"],
		["docker exec c git reset --hard", "git reset --hard"],
		["bash -lc 'git push -f'", "git push --force"],
		["timeout -s KILL 10 git push -f", "git push --force"],
		['git --git-dir="/x y/.git" push -f', "git push --force"],
	])("asks for %s", (command, label) => {
		expect(findDangerousCommands(command)).toContain(label);
	});

	it.each([
		"ls -la",
		"git status",
		"git push origin main",
		"git push -u origin feature",
		"git push --follow-tags",
		"git checkout -b feature",
		"git checkout main",
		"git reset HEAD a.ts",
		"git clean -n",
		"git branch -d merged",
		"npm run format",
		"grep -r perform src",
		"cat docs/rm.txt.bak",
		"find . -name '*.ts'",
		"git stash list; echo done",
		"python3 -m http.server --dd",
		"git rm --cached a",
		"git restore --staged a",
		"npm rm lodash",
		"docker rm c1",
		"grep -n ' rm ' f",
		"rg 'rm -rf'",
		"echo rm",
		"./rm.sh",
		"git branch --format=%(refname)",
		'git commit -m "fix rm handling"',
		'git commit -m "docs: push --force and reset --hard notes"',
		'git commit -m "fix: branch -D handling"',
		"git add rm.ts",
		"git grep -n rm",
		"git log -- rm.ts",
		'git stash push -m "clear"',
		"git worktree remove ../wt",
		"if git diff --quiet; then echo clean; fi",
		"ssh-keygen -t ed25519",
		"nice -n 5 make",
	])("does not ask for %s", (command) => {
		expect(findDangerousCommands(command)).toEqual([]);
	});
});
